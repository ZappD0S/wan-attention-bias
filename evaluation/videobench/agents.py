from pathlib import Path

from . import QwenVLEngine
from .prompts import ACTION_PROMPTS
from .robust_parser import RobustParser


class TextAgent:
    def __init__(self, name: str, prompt_key: str, engine: QwenVLEngine):
        self.name = name
        self.system_prompt = ACTION_PROMPTS[prompt_key]
        self.engine = engine

    def generate_questions(self, target_prompt, current_description, previous_question=None):
        # 1. Exact string from Host.initial_result
        video_prompt = f"This is the text prompt:\n{target_prompt}"

        # 2. Exact description layout from Host.initial_result
        description = f"This is the video's initial description:\n<description>\n{current_description}\n</description>"

        # 3. Exact appendage from Host.question for the second agent
        if previous_question:
            description = (
                description
                + f"\nThis is a question of another assistant:\n<question-one>\n{previous_question}\n</question-one>"
            )

        # 4. Exact message prep from Agent.prepare_message_text
        history_header = "There are the detailed video descriptions of the video:\n\n"
        history_content = description  # In original, this was "\n".join(self.history)
        history_ = (
            history_header
            + "<video's description>\n"
            + history_content
            + "\n</video's description>"
        )

        message_ = video_prompt + "\n\n" + history_

        # 5. Exact final prompt construction from Agent.prepare_message_text
        user_text = (
            message_
            + "\n\nYour questions must be deisplayed in the format: \n<question>\n[your questions] or[I have no question]\n</question>."
            + "\n\nDisplay the results in the specified Output Format"
        )

        # Call engine without video_path -> Text Only mode
        raw_response = self.engine.generate(self.system_prompt, user_text, video_path=None)

        return RobustParser.extract_question(raw_response)


class VideoHost:
    def __init__(
        self,
        engine: QwenVLEngine,
        video_path: str | Path,
        modelname: str = "AI_Model",
        modelmessage: str = "Frames from the video.",
    ):
        self.engine = engine
        self.video_path = video_path
        self.modelname = modelname
        self.modelmessage = modelmessage

    def blind_observation(self) -> str:
        # 1. Exact prompt setup from Host.initial_result
        message_ = "You must think following the 'Evaluation Steps' one by one.\n"

        # In original.py, this was passed as a list of dictionaries to OpenAI.
        # We concatenate it identically for Qwen.
        user_text = (
            message_
            + f"\n\nThese are the frames from the video generated by {self.modelname}\n"
            + self.modelmessage
        )

        raw = self.engine.generate(ACTION_PROMPTS["gpt4o-system"], user_text, self.video_path)
        return RobustParser.extract_section(raw, "Video Description")

    def reflection(self, target_prompt: str, q1: str, q2: str) -> str:
        video_prompt = f"This is the text prompt:\n{target_prompt}"

        # 1. Exact qa_history population from Host.question
        qa_history_list = [
            f"This is the question of the Assistant-one: {q1}\n",
            f"This is the question of the Assistant-two: {q2}\n",
        ]

        # 2. Exact string formatting from Host.answer
        qa_history_header = "\n\nThere are the questions of two assistants:\n\n"
        qa_history_content = "\n".join(qa_history_list)
        qa_history = qa_history_header + "<qa_history>\n" + qa_history_content + "\n</qa_history>\n"

        user_text = (
            video_prompt
            + qa_history
            + f"These are the frames from the video generated by {self.modelname}\n"
            + f"{self.modelmessage}\n"
        )

        raw = self.engine.generate(ACTION_PROMPTS["gpt4o-answer"], user_text, self.video_path)

        desc_part = RobustParser.extract_section(raw, "Descriptions")
        if not desc_part:
            print("[Parsing Warning] Failed to extract 'Descriptions'. Returning full text.")
            desc_part = raw

        return desc_part

    def final_score(self, target_prompt: str, description: str, reflection: str) -> str:
        video_prompt = f"This is the text prompt:\n{target_prompt}"

        # 1. Exact history array population from Host.initial_result & Host.answer
        history_list = [
            f"This is the initial information: \n{description}\n\n",
            f"\nThis is the second information: {reflection}",
        ]

        # 2. Exact formatting from Host.summarize_and_get_results
        history_header = "There are the two informations:\n"
        history_content = "\n".join(history_list)
        history_ = history_header + "<history>\n" + history_content + "\n</history>"

        message_ = (
            "You must think following the 'evaluation steps' one by one.\n\n"
            + history_
            + "\n\n"
            + video_prompt
            + "\n\n"
        )

        user_text = (
            message_ + f"{self.modelmessage}\n" + f"The name of the AI medel is {self.modelname}\n"
        )

        return self.engine.generate(ACTION_PROMPTS["summer-system"], user_text, self.video_path)
